"""
02_system_identification.py - Learning vehicle dynamics from measured time series

QUESTION THIS SCRIPT ANSWERS
    "I have measured road input and suspension travel of a quarter car.
     Can a neural network learn the dynamics - and is that better than
     the alternatives I already know?"

THE "MEASUREMENT"
    A nonlinear quarter-car (cubic spring + asymmetric damper, see common.py) is driven
    with random road input. We record road height u(t) and suspension travel y(t) (like a
    fork / shock stroke sensor) at 100 Hz with a little sensor noise: 60 s for training.

THREE WAYS TO BUILD A MODEL
    (A) Linear ARX  - y[k] = sum a_i*y[k-i] + sum b_j*u[k-j]     (least squares, 1 line)
    (B) NARX with a neural net - same inputs, but y[k] = f_NN(lags)   (nonlinear, black box)
    (C) Grey box - keep the physical quarter-car equations and fit only the 4 uncertain
        parameters (ks, k3, c_reb, c_bump) by simulation-error minimisation.

HOW TO JUDGE THEM  (this is the crucial part - two very different tests)
    * ONE-STEP prediction: predict y[k] from the TRUE past y. Easy; almost every model
      looks great here. It hides the real quality.
    * FREE-RUN simulation: feed the model its OWN outputs and only give it the road.
      Errors accumulate. This is what you need for a simulation model.
    * And: does it work on a rougher road than it was trained on (extrapolation)?

WHAT TO TAKE AWAY (reference run; exact numbers vary with seeds)
    * One-step fit looks good for everybody (linear 94 %, NN 97 %) but free-run fit tells
      the truth: linear ARX 55 %, NN 70 %. The NN helps because the system is nonlinear,
      yet a naive one-step-trained NARX is far from a usable simulation model.
    * On a road twice as rough than in training, the black-box models collapse (linear 19 %,
      NN 28 %): they only know the operating range they have seen. The grey box stays at
      99-100 % because its equations do not care about the amplitude.
    * CAVEAT: the "measurement" is generated by the same equations the grey box uses, so its
      near-perfect result is the BEST case. With a real vehicle, structural errors remain
      (see script 01, world 2) - that residual is what an NN could later learn.
    * Rule of thumb: known physics + few uncertain parameters -> tune parameters.
      Unknown/too complex physics + lots of data -> NN. Often best: combine both.
    * Improving a black-box NN for simulation needs more than a bigger network: train on
      multi-step rollouts, cover the operating range, or let it learn only the residual of a
      physics model.

Run:  python 02_system_identification.py      (~15 s on CPU)
"""
import numpy as np
import torch
import torch.nn as nn
from scipy.optimize import least_squares
import matplotlib.pyplot as plt

from common import (COL, setup_plot_style, save_fig, make_road, simulate_quarter_car,
                    DEFAULT_PARAMS, DT)

setup_plot_style()
torch.manual_seed(0)
torch.set_num_threads(2)

DEC = 2                 # sim step 5 ms -> sample every 2nd step -> 100 Hz
TS = DT * DEC
NA = NB = 8             # number of past outputs / inputs used by the ARX/NARX models
OUTPUT = "d"           # measured output: suspension travel d = zs - zu (like a fork/shock stroke sensor)
SENSOR_NOISE = 0.0002   # 0.2 mm noise on the travel sensor


# ---------------------------------------------------------------------------
# 1. Generate "measured" data
# ---------------------------------------------------------------------------
def measure(seconds, road_std, seed):
    n = int(seconds / DT)
    zr = make_road(n, std=road_std, seed=seed)
    out = simulate_quarter_car(zr)
    rng = np.random.default_rng(seed + 100)
    u = zr[::DEC]
    y = out[OUTPUT][::DEC] + rng.normal(0, SENSOR_NOISE, n // DEC)
    return u, y, zr


u_tr, y_tr, zr_tr = measure(60, 0.015, seed=1)     # training
u_te, y_te, zr_te = measure(30, 0.015, seed=2)     # test, same road roughness
u_ood, y_ood, zr_ood = measure(30, 0.030, seed=3)  # test, TWICE as rough (extrapolation)
print(f"training samples: {len(y_tr)}   y std = {1000 * y_tr.std():.1f} mm   "
      f"(noise std {1000 * SENSOR_NOISE:.1f} mm)")


# ---------------------------------------------------------------------------
# 2. NARX regressors: features = [y[k-1..k-NA], u[k..k-NB+1]],  target = y[k]
#    Note u[k] (the CURRENT input) is included on purpose: with sampled data the current
#    road sample carries information about y[k] (in this test: linear-system fit 80 % -> 93 %).
# ---------------------------------------------------------------------------
def regressors(u, y):
    n0 = max(NA, NB)
    X, T = [], []
    for k in range(n0, len(y)):
        X.append(np.concatenate([y[k - NA:k][::-1], u[k - NB + 1:k + 1][::-1]]))
        T.append(y[k])
    return np.array(X), np.array(T)


def fit_pct(y, yhat):
    """NRMSE fit in %: 100 = perfect, 0 = no better than predicting the mean."""
    return 100 * (1 - np.linalg.norm(y - yhat) / np.linalg.norm(y - y.mean()))


Xtr, Ttr = regressors(u_tr, y_tr)
# standardisation (mean/std from TRAINING data only)
XM, XS = Xtr.mean(0), Xtr.std(0)
TM, TS_ = Ttr.mean(), Ttr.std()

# ---------------------------------------------------------------------------
# (A) Linear ARX by least squares
# ---------------------------------------------------------------------------
theta, *_ = np.linalg.lstsq(np.c_[Xtr, np.ones(len(Xtr))], Ttr, rcond=None)


def step_linear(x):
    return float(x @ theta[:-1] + theta[-1])


# ---------------------------------------------------------------------------
# (B) NARX with a neural net
# ---------------------------------------------------------------------------
def train_nn(X, T, hidden=64, epochs=200, seed=0):
    torch.manual_seed(seed)
    Xn = torch.tensor((X - XM) / XS, dtype=torch.float32)
    Tn = torch.tensor(((T - TM) / TS_).reshape(-1, 1), dtype=torch.float32)
    n_val = int(0.15 * len(Xn))                    # last 15 % of the record = validation
    Xa, Ta, Xv, Tv = Xn[:-n_val], Tn[:-n_val], Xn[-n_val:], Tn[-n_val:]
    net = nn.Sequential(nn.Linear(X.shape[1], hidden), nn.Tanh(),
                        nn.Linear(hidden, hidden), nn.Tanh(), nn.Linear(hidden, 1))
    opt = torch.optim.Adam(net.parameters(), lr=2e-3, weight_decay=1e-5)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, epochs)
    best, state = np.inf, None
    for ep in range(epochs):
        perm = torch.randperm(len(Xa))
        for i in range(0, len(Xa), 256):
            b = perm[i:i + 256]
            opt.zero_grad()
            loss = ((net(Xa[b]) - Ta[b]) ** 2).mean()
            loss.backward()
            opt.step()
        sched.step()
        with torch.no_grad():
            lv = ((net(Xv) - Tv) ** 2).mean().item()
        if lv < best:
            best, state = lv, {k: v.clone() for k, v in net.state_dict().items()}
    net.load_state_dict(state)
    print(f"  NN trained: {sum(p.numel() for p in net.parameters())} parameters, "
          f"best validation MSE (normalised) = {best:.4f}")
    return net


net = train_nn(Xtr, Ttr)


def step_nn(x):
    with torch.no_grad():
        z = torch.tensor(((x - XM) / XS)[None, :], dtype=torch.float32)
        return float(net(z).item()) * TS_ + TM


# ---------------------------------------------------------------------------
# Evaluation: one-step and free-run
# ---------------------------------------------------------------------------
def one_step(step_fn, u, y):
    X, T = regressors(u, y)
    yhat = np.array([step_fn(x) for x in X])
    return T, yhat


def free_run(step_fn, u, y):
    """Feed the model its own outputs. Only the first NA true samples are given."""
    n0 = max(NA, NB)
    yhat = list(y[:n0])
    for k in range(n0, len(y)):
        x = np.concatenate([np.array(yhat[k - NA:k])[::-1], u[k - NB + 1:k + 1][::-1]])
        yhat.append(step_fn(x))
    return np.array(yhat)


# ---------------------------------------------------------------------------
# (C) Grey box: fit 4 physical parameters by simulation-error minimisation
# ---------------------------------------------------------------------------
PNAMES = ["ks", "k3", "c_reb", "c_bump"]
# start 30-50 % away from the truth, as after an imprecise first guess
P0 = np.array([0.7 * DEFAULT_PARAMS["ks"], 0.5 * DEFAULT_PARAMS["k3"],
               1.4 * DEFAULT_PARAMS["c_reb"], 1.4 * DEFAULT_PARAMS["c_bump"]])
N_FIT = int(20 / DT)      # only the first 20 s of the training road are used


def residual(logp):
    p = dict(zip(PNAMES, np.exp(logp)))
    sim = simulate_quarter_car(zr_tr[:N_FIT], p)[OUTPUT][::DEC]
    return (sim - y_tr[:len(sim)]) / SENSOR_NOISE


print("  fitting grey-box parameters (least squares on simulation error) ...")
sol = least_squares(residual, np.log(P0), x_scale=0.3)
P_FIT = dict(zip(PNAMES, np.exp(sol.x)))
print("  parameter    true      start     fitted")
for k, p0 in zip(PNAMES, P0):
    print(f"  {k:8s} {DEFAULT_PARAMS[k]:10.4g} {p0:10.4g} {P_FIT[k]:10.4g}")


def greybox(zr):
    return simulate_quarter_car(zr, P_FIT)[OUTPUT][::DEC]


# ---------------------------------------------------------------------------
# Results
# ---------------------------------------------------------------------------
n0 = max(NA, NB)
res = {}
for name, (u, y, zr) in {"test (same road)": (u_te, y_te, zr_te),
                         "rough road (2x amplitude)": (u_ood, y_ood, zr_ood)}.items():
    r = {}
    for mname, fn in (("Linear ARX", step_linear), ("NARX neural net", step_nn)):
        T, yh1 = one_step(fn, u, y)
        r[mname] = dict(one=fit_pct(T, yh1), free=fit_pct(y[n0:], free_run(fn, u, y)[n0:]),
                        yfree=free_run(fn, u, y))
    yg = greybox(zr)
    r["Grey box (4 par.)"] = dict(one=np.nan, free=fit_pct(y[n0:], yg[n0:len(y)]), yfree=yg[:len(y)])
    res[name] = r

print("\nFIT [%]   (100 = perfect, 0 = as bad as predicting the mean)")
print(f"{'':22s}{'one-step':>10s}{'free-run':>10s}   {'one-step':>10s}{'free-run':>10s}")
print(f"{'':22s}{'--- test, same road ---':>20s}   {'--- rough road ---':>20s}")
for m in ("Linear ARX", "NARX neural net", "Grey box (4 par.)"):
    a, b = res["test (same road)"][m], res["rough road (2x amplitude)"][m]
    fa = "   n/a " if np.isnan(a["one"]) else f"{a['one']:8.1f}"
    fb = "   n/a " if np.isnan(b["one"]) else f"{b['one']:8.1f}"
    print(f"{m:22s}{fa:>10s}{a['free']:10.1f}   {fb:>10s}{b['free']:10.1f}")
print("\n(Grey-box has no one-step mode: it is a simulation model by construction.)")

# ---------------------------------------------------------------------------
# Plots
# ---------------------------------------------------------------------------
MC = {"Linear ARX": COL["aqua"], "NARX neural net": COL["orange"], "Grey box (4 par.)": COL["blue"]}
t = np.arange(len(y_te)) * TS
fig, axes = plt.subplots(2, 1, figsize=(11, 6.2), sharex=True)
for ax, (name, (u, y)) in zip(axes, {"test (same road)": (u_te, y_te),
                                     "rough road (2x amplitude)": (u_ood, y_ood)}.items()):
    sl = slice(int(4 / TS), int(12 / TS))
    ax.plot(t[sl], 1000 * y[sl], color=COL["grey"], lw=2.4, label="measured", zorder=1)
    for m in MC:
        ax.plot(t[sl], 1000 * res[name][m]["yfree"][sl], color=MC[m], lw=1.3,
                label=f"{m}  (fit {res[name][m]['free']:.0f} %)")
    ax.set_ylabel("suspension travel [mm]")
    ax.set_title(f"Free-run simulation - {name}", fontsize=10)
    ax.legend(fontsize=8, ncol=2, loc="upper right")
axes[1].set_xlabel("time [s]")
fig.tight_layout()
save_fig(fig, "02_freerun.png")

fig, ax = plt.subplots(figsize=(7, 3.6))
names = ["test (same road)", "rough road (2x amplitude)"]
w = 0.26
for i, m in enumerate(MC):
    vals = [res[n][m]["free"] for n in names]
    ax.bar(np.arange(2) + (i - 1) * w, vals, w * 0.92, color=MC[m], label=m)
    for x, v in zip(np.arange(2) + (i - 1) * w, vals):
        ax.text(x, v + 1, f"{v:.0f}", ha="center", fontsize=8)
ax.set_xticks(range(2))
ax.set_xticklabels(names)
ax.set_ylabel("free-run fit [%]")
ax.set_ylim(0, 108)
ax.grid(axis="x", visible=False)
ax.legend(fontsize=8, ncol=3, loc="upper center", bbox_to_anchor=(0.5, -0.14))
ax.set_title("Free-run fit: black-box vs. physics-based")
save_fig(fig, "02_fit_summary.png")
